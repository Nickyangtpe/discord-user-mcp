"""Endpoint registry: what the server knows about the Discord user API.

The packaged JSON is generated by ``tools/build_registry.py`` from the
community documentation at docs.discord.food plus this project's curation.
Every entry carries an explicit support status, so the server never pretends
an endpoint exists or works.
"""

from __future__ import annotations

import json
from functools import lru_cache
from importlib import resources
from typing import Iterable, Literal

from pydantic import BaseModel, ConfigDict, Field

from ..security.permissions import Risk

EndpointStatus = Literal["implemented", "documented", "unsupported"]


class EndpointParam(BaseModel):
    model_config = ConfigDict(extra="ignore")

    name: str
    type: str = ""
    required: bool = False
    description: str = ""


class Endpoint(BaseModel):
    model_config = ConfigDict(extra="ignore")

    id: str
    method: str
    path: str
    category: str
    title: str = ""
    summary: str = ""
    risk: Risk | None = None
    status: EndpointStatus
    tools: list[str] = Field(default_factory=list)
    params: dict[str, list[EndpointParam]] = Field(default_factory=dict)
    oauth2_scope: str | None = None
    supports_bot: bool = False
    deprecated: bool = False
    limitations: str = ""
    source: str = ""

    @property
    def requires_approval(self) -> bool:
        return self.risk is not None and self.risk.requires_approval


class UnknownEndpoint(KeyError):
    pass


class Registry:
    def __init__(self, entries: Iterable[Endpoint]) -> None:
        self._by_id: dict[str, Endpoint] = {}
        for entry in entries:
            if entry.id in self._by_id:
                raise ValueError(f"duplicate endpoint id in registry: {entry.id}")
            self._by_id[entry.id] = entry

    @classmethod
    def load(cls) -> "Registry":
        raw = resources.files("discord_user_mcp.api").joinpath("registry_data.json").read_text("utf-8")
        payload = json.loads(raw)
        return cls(Endpoint.model_validate(item) for item in payload["entries"])

    def __len__(self) -> int:
        return len(self._by_id)

    def __iter__(self):
        return iter(self._by_id.values())

    def get(self, endpoint_id: str) -> Endpoint:
        try:
            return self._by_id[endpoint_id]
        except KeyError as exc:
            raise UnknownEndpoint(endpoint_id) from exc

    def tool_endpoints(self) -> dict[str, Endpoint]:
        mapping: dict[str, Endpoint] = {}
        for entry in self._by_id.values():
            for tool in entry.tools:
                if tool in mapping:
                    raise ValueError(f"tool {tool} is mapped to two endpoints")
                mapping[tool] = entry
        return mapping

    def search(
        self,
        *,
        category: str | None = None,
        status: str | None = None,
        query: str | None = None,
        risk: str | None = None,
        limit: int = 50,
        offset: int = 0,
    ) -> tuple[list[Endpoint], int]:
        rows = list(self._by_id.values())
        if category:
            rows = [e for e in rows if e.category == category]
        if status:
            rows = [e for e in rows if e.status == status]
        if risk:
            rows = [e for e in rows if e.risk is not None and e.risk.value == risk]
        if query:
            needle = query.lower()
            rows = [
                e
                for e in rows
                if needle in e.id.lower()
                or needle in e.path.lower()
                or needle in e.title.lower()
                or needle in e.summary.lower()
            ]
        rows.sort(key=lambda e: (e.category, e.path, e.method))
        total = len(rows)
        return rows[offset : offset + limit], total

    def stats(self) -> dict[str, object]:
        counts = {"implemented": 0, "documented": 0, "unsupported": 0}
        categories: dict[str, int] = {}
        for entry in self._by_id.values():
            counts[entry.status] = counts.get(entry.status, 0) + 1
            categories[entry.category] = categories.get(entry.category, 0) + 1
        return {
            "total": len(self._by_id),
            "by_status": counts,
            "by_category": dict(sorted(categories.items())),
            "implemented_endpoints": sum(
                1 for e in self._by_id.values() if e.status == "implemented"
            ),
        }

    @staticmethod
    def render_path(endpoint: Endpoint, values: dict[str, object]) -> str:
        """Substitute path parameters, refusing to invent missing values."""
        import re
        from urllib.parse import quote

        def repl(match: re.Match[str]) -> str:
            name = match.group(1)
            if name not in values:
                raise ValueError(f"missing path parameter {name!r} for {endpoint.id}")
            value = values[name]
            return quote(str(value), safe="@:")

        return re.sub(r"\{([^}]+)\}", repl, endpoint.path)


@lru_cache(maxsize=1)
def get_registry() -> Registry:
    return Registry.load()
